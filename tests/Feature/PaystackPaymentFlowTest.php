    public function test_successful_paystack_payment_activates_pending_subscription(): void
    {
        $user = User::factory()->create();
        $plan = $this->createPlan();

        $subscription = Subscription::create([
            'user_id' => $user->id,
            'plan_id' => $plan->id,
            'status' => 'pending',
            'starts_at' => null,
            'expires_at' => null,
            'next_billing_at' => null,
            'auto_renew' => true,
            'is_trial' => false,
        ]);

        $payment = Payment::create([
            'user_id' => $user->id,
            'subscription_id' => $subscription->id,
            'amount' => 29.99,
            'currency' => 'USD',
            'gateway' => 'paystack',
            'reference' => 'TW-VERIFY-001',
            'status' => 'pending',
        ]);

        $this->mock(PaystackService::class, function ($mock) use ($payment) {
            $mock->shouldReceive('verifyTransaction')
                ->once()
                ->with($payment->reference)
                ->andReturn([
                    'status' => true,
                    'message' => 'Verification successful',
                    'data' => [
                        'status' => 'success',
                        'reference' => $payment->reference,
                        'id' => 123456789,
                        'amount' => 2999,
                        'currency' => 'USD',
                    ],
                ]);
        });

        $response = $this
            ->actingAs($user, 'sanctum')
            ->postJson('/api/payments/verify', [
                'reference' => $payment->reference,
            ]);

        $response->assertStatus(200)
            ->assertJson([
                'message' => 'Payment verified successfully.',
            ]);

        $this->assertDatabaseHas('payments', [
            'id' => $payment->id,
            'status' => 'successful',
            'transaction_id' => (string) $payment->reference,
        ]);

        $this->assertDatabaseHas('subscriptions', [
            'id' => $subscription->id,
            'status' => 'active',
        ]);

        $subscription->refresh();

        $this->assertNotNull($subscription->starts_at);
        $this->assertNotNull($subscription->expires_at);
        $this->assertNotNull($subscription->next_billing_at);
    }

