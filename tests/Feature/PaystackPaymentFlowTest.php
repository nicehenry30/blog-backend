    public function test_authenticated_user_can_initialize_paystack_payment(): void
    {
        $user = User::factory()->create();
        $plan = $this->createPlan();

        $this->mock(PaystackService::class, function ($mock) {
            $mock->shouldReceive('initializeTransaction')
                ->once()
                ->andReturn([
                    'status' => true,
                    'message' => 'Authorization URL created',
                    'data' => [
                        'authorization_url' =>
                            'https://checkout.paystack.com/test',
                        'access_code' => 'test-access-code',
                        'reference' => 'TW-TEST-REFERENCE',
                    ],
                ]);
        });

        /*
         * We cannot control the random reference generated by
         * PaymentService, so the mocked Paystack response reference
         * is accepted independently of it.
         */
        $response = $this
            ->actingAs($user, 'sanctum')
            ->postJson('/api/payments/initialize', [
                'plan_id' => $plan->id,
            ]);

        $response->assertStatus(200)
            ->assertJsonStructure([
                'payment',
                'subscription',
                'authorization_url',
                'access_code',
                'reference',
            ]);

        $this->assertDatabaseHas('subscriptions', [
            'user_id' => $user->id,
            'plan_id' => $plan->id,
            'status' => 'pending',
        ]);

        $this->assertDatabaseHas('payments', [
            'user_id' => $user->id,
            'gateway' => 'paystack',
            'status' => 'pending',
        ]);
    }

